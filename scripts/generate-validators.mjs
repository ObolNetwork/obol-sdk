#!/usr/bin/env node
// Precompiles the JSON schemas in src/schema.ts into plain JavaScript
// validators (ajv "standalone code"), written to src/generated/validators.ts.
//
// Compiling at build time means the SDK never generates code at runtime
// (ajv's compiler uses `new Function`), so consumers can run under a
// Content-Security-Policy without 'unsafe-eval', and ajv is not a runtime
// dependency.
//
// The SDK's custom keywords (src/customKeywords.ts) are `validate`-function
// keywords, which standalone code cannot serialise by itself. Each function is
// pre-registered in ajv's scope with code that names it as an import
// (`customKeywords.<keyword>`), so the generated module calls the same
// functions, in the same place, as ajv did at runtime.
//
// Usage: node scripts/generate-validators.mjs [--check]
//   --check  exit 1 if the committed file is out of date (CI / tests)

import { build } from 'esbuild';
import Ajv, { _, Name } from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src/generated/validators.ts');

// Must match the options src/ajv.ts used to compile at runtime, plus
// standalone ESM output.
export const AJV_OPTIONS = {
  allErrors: true,
  useDefaults: true,
  strict: false,
  $data: true,
  code: { source: true, esm: true, lines: true, optimize: true },
};

/** Imports src/schema.ts and src/customKeywords.ts (TypeScript). */
export async function loadSources() {
  // Bundle them to a temporary ESM module and import that.
  const result = await build({
    stdin: {
      contents: [
        "export * as schemas from './src/schema.ts';",
        "export * as customKeywords from './src/customKeywords.ts';",
      ].join('\n'),
      resolveDir: root,
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    packages: 'external',
    write: false,
    logLevel: 'silent',
  });
  // Inside the repo so the bundle's bare imports (ethers) resolve.
  mkdirSync(join(root, 'node_modules/.cache'), { recursive: true });
  const dir = mkdtempSync(join(root, 'node_modules/.cache/obol-sdk-schemas-'));
  try {
    const file = join(dir, 'schema.mjs');
    writeFileSync(file, result.outputFiles[0].text);
    return await import(pathToFileURL(file).href);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** Exports of schema.ts that are whole payload schemas. */
export function payloadSchemas(mod) {
  return Object.entries(mod)
    .filter(
      ([, value]) =>
        value !== null && typeof value === 'object' && value.type === 'object',
    )
    .sort(([a], [b]) => a.localeCompare(b));
}

export async function generate() {
  const { schemas: schemaModule, customKeywords } = await loadSources();
  const schemas = payloadSchemas(schemaModule);
  const ajv = new Ajv(AJV_OPTIONS);
  for (const def of customKeywords.CUSTOM_KEYWORDS) {
    const validate = customKeywords[def.keyword];
    if (typeof validate !== 'function') {
      throw new Error(`customKeywords.ts must export ${def.keyword}`);
    }
    // ajv dedupes scope values by `ref`, so the keyword's validate function
    // is emitted as `const keywordN = customKeywords.<keyword>`.
    ajv.scope.value('keyword', {
      ref: validate,
      code: _`customKeywords.${new Name(def.keyword)}`,
    });
    ajv.addKeyword({ ...def, validate });
  }
  const refs = {};
  for (const [name, schema] of schemas) {
    // Deep copy: ajv may annotate schema objects.
    ajv.addSchema(structuredClone(schema), name);
    refs[name] = name;
  }
  // ajv calls `validate` keywords with its instance as `this` (`self`), which
  // does not exist in standalone code; the custom keywords don't use `this`.
  const code = standaloneCode(ajv, refs).replaceAll(
    '.call(self, ',
    '.call(undefined, ',
  );
  if (/\bself\b/.test(code)) {
    throw new Error('generated validators still reference `self`');
  }
  return [
    '// @ts-nocheck',
    '/* eslint-disable */',
    '// GENERATED by scripts/generate-validators.mjs from src/schema.ts. Do not edit.',
    '// Regenerate with `yarn generate:validators`.',
    "import * as customKeywords from '../customKeywords.js';",
    code,
    '',
  ].join('\n');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const code = await generate();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {}
    if (current !== code) {
      console.error(
        `${outFile} is out of date with src/schema.ts; run \`yarn generate:validators\`.`,
      );
      process.exit(1);
    }
    console.log('validators up to date');
  } else {
    writeFileSync(outFile, code);
    console.log(`wrote ${outFile}`);
  }
}
